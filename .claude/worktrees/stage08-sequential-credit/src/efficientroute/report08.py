"""Render `reports/08-optimisation.md` — what letting credit cross days bought.

Written to be read by whoever prices the campaign, not by whoever wrote the solver.
The question it answers is not "did the number go down" but **what bought it**: how
much coverage was harvested from passes the car was already making, what slowing
those passes to filming speed cost, and how many days that removed.

The tier table is the point. §3 of the brief asks for each tier separately because
knowing that tier 1 got most of the gain is worth more than the final total — it
says the fix is a bookkeeping change and not a new solver.
"""

from __future__ import annotations

from pathlib import Path

from . import caveat
from . import config as C
from .report import _table
from .report02 import _block, _n

TIER_LABEL = {
    "0": "incumbent — Stage 5's plan, as the control",
    "1": "passive credit — bank the qualifying passes the route already drives",
    "2": "order search — run tier 1 under candidate day orders, keep the best",
    "3": "joint LNS — relocate, swap and merge whole days (not implemented)",
}


def write(a: dict, path: Path = None) -> Path:
    path = Path(path or C.REPORTS / "08-optimisation.md")
    parts = ["# Stage 8 — coverage credit across day boundaries\n"]
    parts.append(
        "Generated by `efficientroute stage8`. Every number is read from\n"
        "`data/derived/08-sequential.json`, which the Stage 8 gate asserts against."
    )
    parts.append(_headline(a))
    parts.append(_tiers(a))
    parts.append(_what_bought_it(a))
    parts.append(_orders(a))
    parts.append(_days(a))
    parts.append(_invariants(a))
    caveat.write(path, _block(*parts))
    return path


def _headline(a: dict) -> str:
    base = a["baseline"]
    tier = a["tiers"].get(a["adopted"])
    if a["adopted"] == "0":
        return (
            "\n## Headline\n\n"
            f"> ## No tier beat the incumbent\n>\n"
            f"> The plan stays at **{base['days']} days, {base['route_h']:.1f} h**.\n"
            "> A negative result, reported rather than engineered away.\n"
        )
    delta = tier["vs_baseline"]
    return (
        "\n## Headline\n\n"
        f"> ## {tier['days']} driving days, {tier['route_h']:.1f} h\n>\n"
        f"> Down from **{base['days']} days and {base['route_h']:.1f} h** — "
        f"**{abs(delta['days'])} fewer day{'s' if abs(delta['days']) != 1 else ''}** "
        f"and **{abs(delta['route_h']):.1f} h less driving "
        f"({abs(delta['route_pct']):.1f}%)**.\n>\n"
        f"> Bought by crediting **{_n(tier['bonus_passes'])} passes** — "
        f"**{tier['bonus_km']:.1f} km** — the car was already driving,\n"
        f"> for **{tier['slowing_h'] * 60:.0f} minutes** of holding to filming speed.\n"
    )


def _tiers(a: dict) -> str:
    rows = []
    base = a["baseline"]
    for name in sorted(a["tiers"]):
        tier = a["tiers"][name]
        if name == "0":
            rows.append(["0", TIER_LABEL["0"], _n(base["days"]),
                         f"{base['route_h']:.2f}", "—", "—"])
            continue
        delta = tier["vs_baseline"]
        rows.append([
            name, TIER_LABEL.get(name, ""), _n(tier["days"]),
            f"{tier['route_h']:.2f}",
            f"{delta['days']:+d}", f"{delta['route_h']:+.2f} h ({delta['route_pct']:+.1f}%)",
        ])
    body = _table(["Tier", "What it does", "Days", "Driving h", "Δ days", "Δ hours"], rows)
    return (
        "\n## 1. What each tier bought\n\n" + body +
        f"\n**Adopted: tier {a['adopted']}.** A tier is taken only if it wins outright — "
        "fewer days first, then fewer hours. A tie keeps the incumbent, because a plan "
        "already checked and reported on is worth more than an equal one that is not.\n"
    )


def _what_bought_it(a: dict) -> str:
    if a["adopted"] == "0":
        return ""
    tier = a["tiers"][a["adopted"]]
    rule = a["credit_rule"]
    per_km = (tier["slowing_h"] * 3600 / tier["bonus_km"]) if tier["bonus_km"] else 0.0
    return (
        "\n## 2. Where the saving comes from\n\n"
        "Stage 4 gives each required arc to one day and Stage 5 solves that day as a "
        "closed circuit over its own zone, so credit was **per-day**: the car drove a "
        "street on day 3 while repositioning, earned nothing, and came back on day 7 "
        "to film it. Nothing about the camera changed here — it was always on. What "
        "changed is that a pass driven at filming speed now discharges the "
        "requirement **whenever it happens**.\n\n"
        + _table(
            ["", "Value"],
            [
                ["Passes credited that the route already drove", _n(tier["bonus_passes"])],
                ["Coverage harvested from them", f"{tier['bonus_km']:.2f} km"],
                ["Time spent holding those passes to filming speed",
                 f"{tier['slowing_h'] * 60:.1f} min"],
                ["Cost per kilometre harvested", f"{per_km:.1f} s/km"],
                ["Driving hours saved", f"{abs(tier['vs_baseline']['route_h']):.2f} h"],
                ["Days removed", _n(abs(tier["vs_baseline"]["days"]))],
                ["Zone splits Stage 5 needed that this plan did not",
                 _n(max(0, a.get("baseline_splits", 0) - len(tier.get("splits", []))))],
            ],
        )
        + "\n**The trade is extremely one-sided, and that is the finding.** Holding a "
        "pass to filming speed costs almost nothing on the streets where it matters: "
        "a residential arc is already driven near the cap, so the slowdown is seconds, "
        "while the revisit it replaces costs a return trip across the zone. On "
        "`capture_quality = \"reduced\"` arcs — motorway and trunk, exempt from the "
        f"{rule['speed_max_kmh']:.0f} km/h rule under SPEC §3.2 — the credit is "
        "free outright.\n\n"
        "**Where the days go.** A day is removed not by shortening it but by emptying "
        "it: once earlier days have filmed enough of a later zone, that zone owes "
        "nothing and its day disappears. The rest of the saving is zones that no "
        "longer overrun their window, so Stage 5's split never has to happen.\n"
    )


def _orders(a: dict) -> str:
    """The order search — §4 asks whether more compute would still be buying anything."""
    attempts = a.get("attempts") or []
    if len(attempts) < 2:
        return ""
    best = min(attempts, key=lambda r: (r["days"], r["route_h"]))
    rows = [
        [r["order"], _n(r["days"]), f"{r['route_h']:.2f}",
         "**best**" if r is best else ""]
        for r in attempts
    ]
    spread_days = max(r["days"] for r in attempts) - min(r["days"] for r in attempts)
    spread_h = max(r["route_h"] for r in attempts) - min(r["route_h"] for r in attempts)
    return (
        "\n## 3. Which day goes first, and why it matters\n\n"
        + _table(["Candidate order", "Days", "Driving h", ""], rows)
        + f"\n**The order is worth {spread_days} day"
        f"{'s' if spread_days != 1 else ''} and {spread_h:.2f} h across these "
        "candidates.** Credit lands on whichever days run first, so the sequence "
        "decides how much later work disappears — and Stage 4's far-zones-first order "
        "was chosen to shorten depot legs by a rule that predates crediting entirely. "
        "It is not the best order once credit exists.\n\n"
        "The seeded shuffles are the control. If they matched the principled orders "
        "the search would be finding noise; that they do not is what says the "
        "principle is real.\n"
    )


def _days(a: dict) -> str:
    rows = []
    for day in a.get("days", []):
        rows.append([
            _n(day["day"]), day["date"], _n(day["zone"]),
            f"{day['route_h']:.2f}", f"{day['day_h']:.2f}",
            _n(day["bonus_passes"]), f"{day['bonus_km']:.1f}",
            f"{day['slowing_h'] * 60:.1f}",
        ])
    if not rows:
        return ""
    return (
        "\n## 4. The days\n\n"
        + _table(["Day", "Date", "Zone", "Driving h", "Day h", "Credited passes",
                  "Credited km", "Slowing min"], rows)
        + "\n`Credited passes` are streets this day filmed that some **other** day was "
        "scheduled to come back for. They are the mechanism, and they fall away "
        "towards the end of the campaign because by then there is little left that "
        "another day still owes.\n"
    )


def _invariants(a: dict) -> str:
    if a["adopted"] == "0":
        return ""
    tier = a["tiers"][a["adopted"]]
    return (
        "\n## 5. Why the saving is real\n\n"
        "A saving of this kind is easy to fake in three ways, so each is checked:\n\n"
        + _table(
            ["Could be faked by", "Invariant", "Result"],
            [
                ["Not actually filming the streets",
                 "**I1**, campaign-wide: every requirement discharged somewhere",
                 f"{_n(tier['undischarged_passes'])} left undischarged"],
                ["Filming them too fast to count",
                 "**I9**: every credited pass satisfies the Stage 6 rule",
                 f"{_n(len(tier['i9_failures']))} failures"],
                ["Never paying for the slowdown",
                 "**I10**: credited deadhead passes costed at capture time",
                 "holds" if tier["i10_ok"] else "**FAILS**"],
                ["Running overlong days",
                 "**I4**: no day exceeds its window after slowing",
                 f"{_n(tier['days_over_window'])} over"],
            ],
        )
        + "\n**I9 is asserted against `coverage.qualifies` — the same function Stage 6 "
        "applies to a real GPS trace.** One implementation, two callers. If plan-time "
        "and run-time crediting were written separately they would drift, and the "
        "plan would bank coverage the rig does not deliver: the exact failure Stage 6 "
        "exists to catch, arriving a stage earlier and much harder to see.\n\n"
        "**I1 changed shape and the old form was deleted, not kept alongside.** "
        "Asserting a street was filmed *on its assigned day* would now fail a correct "
        "plan — that is precisely the constraint this stage removes.\n"
    )
