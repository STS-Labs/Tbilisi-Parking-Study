# --------------------------------------------------------------------------- gate


def _gate(a: dict) -> str:
    meta = a["meta"]
    variants = a["campaign"]["variants"]
    return (
        "\n## 7. Gate\n\n"
        + _table(
            ["Assertion", "Value"],
            [
                ["Included arcs with positive `capture_time_s`", _n(meta["included_arc_count"])],
                ["Required traversals", _n(meta["required_traversals"])],
                ["Σ `capture_time_s` over required traversals",
                 f"{_h(a['capture_hours'])} h"],
                ["`service_role` reconciliation", "≤ 0.05 km per bucket (gate: 1 km)"],
                ["Speeds above 40 km/h on required traversals",
                 "only where `capture_quality = \"reduced\"` (I7)"],
                ["Sensitivity span", "λ ∈ " + ", ".join(
                    _f(v, 2) for v in a["campaign"]["sensitivity_levels"])],
                ["Variants evaluated", " / ".join(r["variant"] for r in variants)],
                ["`network.gpkg` sha256", f"`{meta['arcs_sha256'][:16]}…`"],
            ],
            numeric=False,
        )
        + "\n\n### Non-goals honoured\n\n"
        "No routing. No zoning. No lower bound. No service road excluded — `service_role` is\n"
        "a column and variant A is still what the pipeline builds. No variant chosen.\n"
    )
