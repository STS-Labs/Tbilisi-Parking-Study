"""Render `reports/02-time-model.md` from the Stage 2 artifact.

Every number is read from `data/derived/02-time-model.json`, which the Stage 2
gate asserts against, so the reader and the gate cannot disagree.
"""

from __future__ import annotations

from pathlib import Path

from . import caveat
from . import config as C
from . import servicerole
from .report import _km, _pct, _table


def _block(*chunks: str) -> str:
    """Join chunks with exactly one blank line between them.

    Markdown needs a blank line between a table and the paragraph after it, and
    building that by hand across a report this size is how a table ends up
    silently swallowed into a sentence.
    """
    return "\n\n".join(c.strip("\n") for c in chunks if c.strip()) + "\n"


def _n(value) -> str:
    return f"{value:,}"


def _h(value: float) -> str:
    return f"{value:,.1f}"


def _f(value: float, places: int = 2) -> str:
    return f"{value:,.{places}f}"


def write(a: dict, path: Path = C.TIME_REPORT_MD) -> Path:
    parts: list[str] = ["# Stage 2 — time & capture model\n"]
    parts.append(
        "Generated by `efficientroute stage2`. Every number below is read from\n"
        "`data/derived/02-time-model.json`, which the Stage 2 gate asserts against.\n"
    )
    parts.append(_headline(a))
    parts.append(_item0(a))
    parts.append(_item1(a))
    parts.append(_item2(a))
    parts.append(_item3(a))
    parts.append(_findings(a))
    parts.append(_gate(a))

    path.parent.mkdir(parents=True, exist_ok=True)
    caveat.write(path, _block(*parts))
    return path


# --------------------------------------------------------------------- headline


def _headline(a: dict) -> str:
    variants = {r["variant"]: r for r in a["campaign"]["variants"]}
    A = variants["A"]
    sweep = a["campaign"]["sensitivity"]
    low = min(r["days"] for r in sweep if r["scale"] > 0)
    high = max(r["days"] for r in sweep)
    turn = a["campaign"]["turn_sensitivity"]
    speed = a["speed"]

    return (
        "\n## Headline\n\n"
        f"> ## {_h(A['work_hours'])} hours of capture work — **{_h(A['days'])} days** as built\n"
        f">\n"
        f"> {_km(A['required_km'])} km of required traversal at a work-weighted\n"
        f"> **{_f(speed['mean_capture_kmh'], 1)} km/h**, plus {_h(A['turn_hours'])} h of turn time,\n"
        f"> against a productive day of {_f(C.SHIFT_HOURS - C.BREAK_HOURS, 2)} h before depot legs.\n"
        f">\n"
        f"> Across the whole congestion range the estimate moves\n"
        f"> **{_h(low)} – {_h(high)} days**. Across the turn-time range it moves\n"
        f"> **{_h(turn['min_exit']['days'])} – {_h(turn['mean_exit']['days'])} days**.\n"
        "\n"
        "**This is a floor, not a forecast.** It counts capture time and turn time and\n"
        "nothing else. Repositioning between required arcs — deadhead — is what Stage 3's\n"
        "lower bound exists to measure, and no number for it appears here, because none is\n"
        "yet earned. §5.3 shows the slope without asserting a point on it.\n"
    )


