def _item0(a: dict) -> str:
    parts = ["\n## 1. `service_role` — carrying the service decision forward\n"]
    parts.append(
        "SPEC §2.1 leaves `highway=service` open and Stage 0b closed the tag route: 92.2% of\n"
        "service arcs carry no `service=*` value at all, so the subtag cannot decide anything\n"
        "for the bulk of 2,193 km. **Connectivity can.** Collapse the service-only arcs into\n"
        "undirected components and ask each component how many *distinct* non-service nodes\n"
        "it touches.\n"
    )
    parts.append(
        _table(
            ["`service_role`", "Rule", "Meaning"],
            [
                ["`through`", "component touches ≥ 2", "carries traffic between streets — functionally a street"],
                ["`spur`", "exactly 1", "dead-end tree: driveway, yard, parking aisle"],
                ["`orphan`", "0", "unreachable from the street network"],
            ],
            numeric=False,
        )
    )
    parts.append(
        "\nBoth sides of the test use **included** arcs only. An `access=private` or barriered\n"
        "arc is not a door the camera car can drive through, so counting it as one would\n"
        "promote gated yards to through routes — it moves 45.5 km out of `orphan` on evidence\n"
        "the car cannot use. That is the §1.1-consistent reading: connectivity you cannot\n"
        "drive is not connectivity.\n"
    )

    parts.append("\n### Reconciliation against the stage brief\n")
    reference = a.get("service_role_reference", servicerole.REFERENCE_KM)
    for label, title in (
        ("all_service", "All service"),
        ("untagged_service", "Untagged service"),
    ):
        block = a["service_role"][label]
        rows = []
        for row in block["rows"]:
            expected = reference[label][row["service_role"]]
            rows.append(
                [
                    f"`{row['service_role']}`",
                    _km(row["centerline_km"]),
                    _pct(row["share"] * 100),
                    _km(expected),
                    f"{row['centerline_km'] - expected:+.2f}",
                    _n(row["arc_count"]),
                ]
            )
        rows.append(
            [
                "**total**",
                f"**{_km(block['centerline_km'])}**",
                "",
                f"**{_km(reference[label]['total'])}**",
                f"**{block['centerline_km'] - reference[label]['total']:+.2f}**",
                "",
            ]
        )
        parts.append(f"\n**{title}** — centreline km, pair representatives only\n")
        parts.append(
            _table(["`service_role`", "km", "share", "reference km", "Δ", "arcs"], rows)
        )

    parts.append(
        "\nEvery bucket reconciles to the reference measurement to within 0.05 km, on the\n"
        "first definition tried. The gate asserts 1 km per bucket, so the rule cannot drift\n"
        "meaning without a test failing.\n"
        "\n**Nothing was changed and nothing was excluded.** Variant A remains what the\n"
        "pipeline builds; `service_role` is a column, not a filter. §5.2 prices the choice in\n"
        "hours so Stage 4 can make it.\n"
    )
    return _block(*parts)


