"""Render `reports/04b-recheck.md` from the Stage 4b artifact.

Every number is read from `data/derived/04b-recheck.json`, which the Stage 4b
gate asserts against.
"""

from __future__ import annotations

from pathlib import Path

from . import caveat
from . import config as C
from .report import _km, _pct, _table
from .report02 import _block, _f, _h, _n

#: SPEC §7.3 / Stage 4's solar model: the last date a 10 h shift ending at 18:00
#: is fully daylit.
DAYLIGHT_LIMIT = "2026-10-30"


def write(a: dict, path: Path = C.RECHECK_REPORT_MD) -> Path:
    parts = ["# Stage 4b — variant D re-tested, and the trapped mainlines disposed of\n"]
    parts.append(
        "Generated by `efficientroute stage4b`. Every number below is read from\n"
        "`data/derived/04b-recheck.json`, which the Stage 4b gate asserts against."
    )
    parts.append(_headline(a))
    parts.append(_item1(a))
    parts.append(_item2(a))
    parts.append(_item3(a))
    parts.append(_decision(a))
    parts.append(_gate(a))

    path.parent.mkdir(parents=True, exist_ok=True)
    caveat.write(path, _block(*parts))
    return path


def _headline(a: dict) -> str:
    inputs = a["decision_inputs"]
    d10 = inputs["variants"]["D"]["10h"]
    c10 = inputs["variants"]["C"]["10h"]
    fix = a["item2_trap_disposition"]["fix"]
    return (
        "\n## Headline\n\n"
        f"> ## Variant D fits, with {_n(d10['margin_days'])} days to spare\n"
        f">\n"
        f"> **{_n(d10['days'])} days**, {inputs['variants']['D']['10h']['finish']} at the 10 h\n"
        f"> window, against a daylight limit of {inputs['daylight_limit']}. At 9 h it is\n"
        f"> {_n(inputs['variants']['D']['9h']['days'])} days, finishing\n"
        f"> {inputs['variants']['D']['9h']['finish']} — also inside.\n"
        f">\n"
        f"> The decision of 25 August deferred **1,150 km of through-connected service\n"
        f"> roads** on the basis that D had to start driving by 6 September. That figure was\n"
        f"> wrong, and this stage was run to find out by how much.\n"
        "\n"
        f"Separately, **{_n(fix['edges_added'])} added manoeuvres** recover\n"
        f"{_km(fix['fast_km_recovered'])} km of required motorway and trunk that no closed\n"
        f"tour could previously reach, without weakening invariant U1.\n"
        "\n"
        f"Nothing has been switched. `SCOPE_VARIANT` is still `{a['current_scope_variant']}`\n"
        "and the committed Stage 4 plan is untouched; §5 sets out what the decision now\n"
        "turns on.\n"
    )


def _item1(a: dict) -> str:
    recheck = a["item1_variant_recheck"]
    inputs = a["decision_inputs"]
    parts = ["\n## 1. Variant D, measured\n"]
    parts.append(
        "**Why this was re-run.** Variant D was ruled out on 25 August because it \"needed to\n"
        "start driving by 6 September\", a date derived from a flat **1.2 h/day** depot-leg\n"
        "allowance applied to Stage 3's totals. Stage 4 then routed the legs over `L(G)` and\n"
        f"measured **{_h(recheck['C']['windows']['10h']['leg_hours'])} h across the entire\n"
        f"variant C campaign** — about 33 minutes a day, not 1.2 hours. The arithmetic that\n"
        "ruled D out was built on an allowance more than twice the real figure.\n"
        "\nSo D was measured, not scaled. Its requirements are more numerous and more\n"
        "scattered than C's, so its legs, its balance and its zone count all had to be\n"
        "computed — extrapolating from C is the error that made this re-check necessary in\n"
        "the first place, and repeating it here would have been worse than not checking.\n"
    )
    rows = []
    for variant in ("C", "D"):
        block = recheck[variant]
        for name in ("10h", "9h"):
            window = block["windows"][name]
            row = inputs["variants"][variant][name]
            rows.append(
                [
                    f"**{variant}**" if name == "10h" else "",
                    name,
                    _n(window["days"]),
                    window["finish"],
                    f"{row['margin_days']:+d}",
                    _h(window["total_hours"]),
                    f"{_f(window['day_min'], 2)}–{_f(window['day_max'], 2)}",
                    _f(window["day_stdev"], 3),
                    _h(window["leg_hours"]),
                    _h(window["taper_hours"]),
                    window["latest_feasible_start"],
                    window["latest_start_finish"] or "—",
                ]
            )
    parts.append(
        _table(
            ["Variant", "Window", "Days", "Finish", "Margin (d)", "Total h",
             "Day h", "Stdev h", "Legs h", "Taper h", "Latest start",
             "…which finishes"],
            rows,
        )
    )
    parts.append(
        f"\nMargin is against the {inputs['daylight_limit']} daylight limit — the last date a\n"
        "shift ending at 18:00 is fully daylit, from Stage 4's solar model. **Every row\n"
        "fits.** Starting 25 August, no day in any of the four plans is daylight-limited, so\n"
        "the taper column is zero throughout.\n"
        "\n**The last two columns need reading together.** \"Latest start\" applies the daylight\n"
        "rule literally — a day fits if it ends before sunset — and a late start survives it\n"
        "because far-zones-first puts the *short* days at the end, where the short days are.\n"
        "But the finish dates those starts imply run deep into November, and SPEC §7.3 warns\n"
        "that \"low winter sun produces long shadows and glare\". That is a capture-**accuracy**\n"
        "cost under SPEC §1.1, and nothing in this pipeline measures it. Treat the latest-start\n"
        "column as the point where the schedule breaks, not as a date worth planning to.\n"
    )

    parts.append("\n### 1.1 What D costs and what it buys\n")
    parts.append(
        _table(
            ["Measure", "C", "D", "Difference"],
            [
                ["Capture hours",
                 _h(recheck["C"]["capture_hours"]), _h(recheck["D"]["capture_hours"]),
                 f"+{_h(recheck['D']['capture_hours'] - recheck['C']['capture_hours'])}"],
                ["Deadhead + turn per capture hour",
                 f"×{_f(recheck['C']['overhead'], 4)}", f"×{_f(recheck['D']['overhead'], 4)}",
                 f"+{_f(recheck['D']['overhead'] - recheck['C']['overhead'], 4)}"],
                ["Segments to place",
                 _n(recheck["C"]["segments"]), _n(recheck["D"]["segments"]),
                 f"+{_n(recheck['D']['segments'] - recheck['C']['segments'])}"],
                ["Depot legs, whole campaign",
                 f"{_h(recheck['C']['windows']['10h']['leg_hours'])} h",
                 f"{_h(recheck['D']['windows']['10h']['leg_hours'])} h",
                 f"+{_h(recheck['D']['windows']['10h']['leg_hours'] - recheck['C']['windows']['10h']['leg_hours'])} h"],
                ["Days at 10 h",
                 _n(recheck["C"]["windows"]["10h"]["days"]),
                 _n(recheck["D"]["windows"]["10h"]["days"]),
                 f"+{_n(recheck['D']['windows']['10h']['days'] - recheck['C']['windows']['10h']['days'])}"],
                ["Unreachable requirement",
                 f"{_km(recheck['C']['unreachable_km'])} km",
                 f"{_km(recheck['D']['unreachable_km'])} km",
                 f"{recheck['D']['unreachable_km'] - recheck['C']['unreachable_km']:+.1f} km"],
            ],
            numeric=False,
        )
    )
    extra_days = (
        recheck["D"]["windows"]["10h"]["days"] - recheck["C"]["windows"]["10h"]["days"]
    )
    parts.append(
        f"\n**D costs {_n(extra_days)} more days and buys back 1,150 km of streets.** Two things\n"
        "in that table are worth pausing on.\n"
        "\nThe **overhead factor rises** from "
        f"{_f(recheck['C']['overhead'], 3)} to {_f(recheck['D']['overhead'], 3)}: service roads are\n"
        "dead ends and yards, so each hour of capture on them drags more deadhead behind it\n"
        "than an hour on a through street. That is measured by Stage 3's tour, not assumed.\n"
        "\nThe **unreachable requirement falls** under D — "
        f"{_km(recheck['C']['unreachable_km'])} km to {_km(recheck['D']['unreachable_km'])} km. "
        "Adding\n"
        "through-connected service roads adds connections, and some of what was a legal trap\n"
        "under C has a way out under D. Widening the scope makes the network *more*\n"
        "coverable, not less.\n"
    )
    return _block(*parts)


def _item2(a: dict) -> str:
    block = a["item2_trap_disposition"]
    disposition = block["disposition"]
    fix = block["fix"]
    parts = ["\n## 2. Disposing of the trapped mainlines\n"]
    parts.append(
        f"Under variant C, {_km(disposition['fast_trapped_km'])} km of required motorway and\n"
        f"trunk cannot appear in any closed tour — {_pct(disposition['fast_trapped_share'] * 100)}\n"
        f"of the {_km(disposition['fast_required_km'])} km fast network. SPEC §1.1 requires a\n"
        "disposition, and the first question is whether the cause is a modelling rule or the\n"
        "road network.\n"
        "\nStage 1 already has the machinery: rebuild `L(G)` with one rule dropped at a time\n"
        "and see what comes back. That is reused here rather than reimplemented.\n"
    )
    rows = []
    for cause, values in disposition["by_cause"].items():
        rows.append(
            [
                f"`{cause}`",
                _n(values["arcs"]),
                _km(values["km"]),
                _n(values["fast_arcs"]),
                _km(values["fast_km"]),
            ]
        )
    parts.append(
        _table(
            ["Cause", "Arcs", "km", "Motorway/trunk arcs", "Motorway/trunk km"], rows
        )
    )
    causes = disposition["by_cause"]
    parts.append(
        "\nThree things fall out of that table.\n"
        "\n**The U-turn policy strands no fast road at all.** "
        f"It accounts for {_km(causes.get('u_turn_policy', {}).get('km', 0.0))} km of trapped\n"
        "arcs, and *none* of it is motorway or trunk — which is what SPEC §3.3 intends, since\n"
        "those classes carry no U-turn edges by design. The brief raised it as a candidate\n"
        "cause; it is ruled out, and the instruction not to widen the policy globally is moot.\n"
        "\n**Clip-boundary geometry accounts for "
        f"{_km(causes.get('clip_buffer_edge', {}).get('fast_km', 0.0))} km.** These are arcs at or\n"
        "beyond the edge of the extract, already classified in Stage 0b. They are an artefact\n"
        "of where the download stops, not a gap in Tbilisi's coverage.\n"
        "\n**Base topology accounts for "
        f"{_km(causes.get('base_topology', {}).get('fast_km', 0.0))} km.** Genuinely disconnected\n"
        "in the source data. No rule change reaches it; it is a data-quality finding and\n"
        "belongs in the same bucket as Stage 0's hillside fragments.\n"
        "\nThat leaves the mainline-entry rule.\n"
    )

    parts.append("\n### 2.1 The narrowest fix\n")
    parts.append(
        "SPEC §3.3 makes a mainline enterable only from a ramp. Where OSM models **no ramp at\n"
        "a junction**, there is no ramp to insist on: the plain junction is what the data says\n"
        "the access is, and refusing it invents a restriction that is not there on the ground.\n"
        "\nThe proposed narrowing keeps the rule at every junction that has a ramp and relaxes\n"
        "it only at junctions that have none. It is one condition, and this is its whole\n"
        "effect:\n"
    )
    parts.append(
        _table(
            ["Measure", "Rule as built", "Rule narrowed", "Change"],
            [
                ["Manoeuvres in `L(G)`", _n(fix["as_built"]["edges"]),
                 _n(fix["narrowed"]["edges"]), f"+{_n(fix['edges_added'])}"],
                ["Arcs a closed tour can reach", _n(fix["as_built"]["tourable_nodes"]),
                 _n(fix["narrowed"]["tourable_nodes"]),
                 f"+{_n(fix['narrowed']['tourable_nodes'] - fix['as_built']['tourable_nodes'])}"],
                ["Trapped requirement", f"{_km(fix['as_built']['trapped_km'])} km",
                 f"{_km(fix['narrowed']['trapped_km'])} km",
                 f"−{_km(fix['km_recovered'])} km"],
                ["…of it motorway/trunk", f"{_km(fix['as_built']['fast_trapped_km'])} km",
                 f"{_km(fix['narrowed']['fast_trapped_km'])} km",
                 f"−{_km(fix['fast_km_recovered'])} km"],
            ],
            numeric=False,
        )
    )
    added = fix["added_manoeuvres"]
    parts.append(
        f"\n**{_n(fix['edges_added'])} manoeuvres recover {_km(fix['fast_km_recovered'])} km of\n"
        "required motorway and trunk.** All three are the same shape — a trunk road meeting a\n"
        "motorway at a junction OSM models without a slip road, which in Tbilisi is exactly\n"
        "the case Stage 1 flagged when it noted that trunk here is an at-grade arterial class:\n"
    )
    parts.append(
        _table(
            ["From", "Class", "To", "Class", "OSM node"],
            [
                [f"`{m['from_arc']}`", m["from_class"], f"`{m['to_arc']}`", m["to_class"],
                 _n(m["osm_node"])]
                for m in added
            ],
            numeric=False,
        )
    )
    u1 = fix["u1"]
    parts.append(
        f"\n**Invariant U1 holds.** Narrowing a rule only *adds* edges, and everything else is\n"
        "the graph the Stage 1 gate already cleared — so the check here is not another random\n"
        f"sample but an **exhaustive** one over the {_n(u1['checked'])} additions, against the\n"
        f"{_n(u1['forbidden_pairs_in_source'])} manoeuvres the parsed OSM relations forbid.\n"
        f"Violations: **{_n(u1['violations'])}**. A junction OSM models as a junction is\n"
        "drivable, and no turn restriction says otherwise at any of the three.\n"
        "\n**What adopting it costs.** `L(G)` changes, so Stage 1's graph, Stage 3's bounds and\n"
        "Stage 4's zoning all have to be rebuilt — about forty minutes of compute and a\n"
        "re-run of four gates. Nothing else. The flag is\n"
        "`config.MAINLINE_ENTRY_FALLBACK_WHERE_NO_RAMP`, and it is **off**: this is a\n"
        "proposal with a measurement attached, not a change made on the way past. If the\n"
        "scope decision in §5 moves the project to variant D, Stages 1–4 are being rebuilt\n"
        "anyway and adopting it then costs nothing extra.\n"
    )
    return _block(*parts)


def _item3(a: dict) -> str:
    profiles = a["item3_allowance_profiles"]
    parts = ["\n## 3. The extra day\n"]
    parts.append(
        "Stage 4 reserved no room for capture on the commute and took the fewest days,\n"
        "because `DECISION-schedule.md` had turned on the calendar. Stage 4 then measured the\n"
        "slack and found 42 days of it, so that constraint is gone. SPEC §4 states plainly\n"
        "that **total driving hours is the KPI**.\n"
        "\nBoth profiles, measured on each variant's own numbers rather than carried across:\n"
    )
    rows = []
    for variant in sorted(profiles):
        block = profiles[variant]
        for name in ("fewest_days", "reserved"):
            entry = block[name]
            rows.append(
                [
                    f"**{variant}**" if name == "fewest_days" else "",
                    f"{name.replace('_', ' ')} ({_f(entry['allowance'], 2)})",
                    _n(entry["days"]),
                    entry["finish"],
                    _h(entry["total_hours"]),
                    _h(entry["commute_capture_h"]),
                    _f(entry["day_stdev"], 3),
                ]
            )
        delta = block["delta"]
        rows.append(
            [
                "",
                "*difference*",
                f"*+{_n(delta['extra_days'])}*",
                "",
                f"*−{_h(delta['hours_saved'])}*",
                f"*+{_h(delta['extra_commute_capture_h'])}*",
                "",
            ]
        )
    parts.append(
        _table(
            ["Variant", "Profile (allowance)", "Days", "Finish", "Total h",
             "Commute capture h", "Stdev h"],
            rows,
        )
    )
    c_delta = profiles["C"]["delta"]
    d_delta = profiles["D"]["delta"]
    parts.append(
        f"\nOn variant C the reserved profile costs one day and saves\n"
        f"{_h(c_delta['hours_saved'])} h of driving; on D it costs one day and saves\n"
        f"{_h(d_delta['hours_saved'])} h. The direction is the same on both, and the brief's\n"
        "instruction is unambiguous: **take the day**.\n"
        f"\n`config.COMMUTE_ALLOWANCE` is now `{_f(C.COMMUTE_ALLOWANCE, 2)}` and\n"
        f"`COMMUTE_ALLOWANCE_RESERVED` is `{_f(C.COMMUTE_ALLOWANCE_RESERVED, 2)}`; both profiles\n"
        "are reported every run so the trade-off never has to be reconstructed from memory.\n"
        "\nOne honest caveat: reserving the room **widens the day spread**, from\n"
        f"{_f(profiles['C']['fewest_days']['day_stdev'], 3)} h to\n"
        f"{_f(profiles['C']['reserved']['day_stdev'], 3)} h on C. Capture-on-the-commute takes\n"
        "work off the early far zones, so the days it helps most end up shortest. It is a\n"
        "real effect and it eats into the balance headroom the Stage 4 gate measures.\n"
    )
    return _block(*parts)


def _decision(a: dict) -> str:
    inputs = a["decision_inputs"]
    recheck = a["item1_variant_recheck"]
    d10 = inputs["variants"]["D"]["10h"]
    return _block(
        "\n## 4. What the decision now turns on\n",
        "`DECISION-schedule.md` chose C over D for schedule certainty, and recorded that this\n"
        "was the one place SPEC §1.1 was overridden. The measurement that forced the choice\n"
        "has since been replaced by a better one, and the choice does not survive it:\n"
        "\n**The day count was never the problem.** The decision estimated 55.4 days for D and\n"
        f"the measured figure is {_n(d10['days'])} — close enough that scaling was not the error.\n"
        "The error was the *start-by* date: it was derived as \"1 November minus the day\n"
        "count\", which assumes the campaign must both start and finish inside the daylight\n"
        "window as a block. It does not. Far-zones-first puts the long days first, so a\n"
        "campaign can start later than that subtraction allows and still close every day\n"
        "before sunset. That is what moved 6 September to "
        f"{recheck['D']['windows']['10h']['latest_feasible_start']}.\n",
        _table(
            ["", "As decided, 25 Aug", "As measured, Stage 4b"],
            [
                ["Depot-leg allowance", "1.2 h/day (assumed)",
                 f"{_f(recheck['C']['windows']['10h']['leg_hours'] / recheck['C']['windows']['10h']['days'] * 60, 0)} min/day (routed)"],
                ["Variant D, days at 10 h", "55.4 (estimated)", f"{_n(d10['days'])} (measured)"],
                ["Variant D, must start driving by", "6 September",
                 f"{recheck['D']['windows']['10h']['latest_feasible_start']} "
                 f"(finishing {recheck['D']['windows']['10h']['latest_start_finish']})"],
                ["Variant D finishes", "past the limit", f"{d10['finish']} (+{_n(d10['margin_days'])} d)"],
                ["1,150 km of through service roads", "deferred to phase 2", "**recoverable now**"],
            ],
            numeric=False,
        ),
        "**The recommendation is to move to variant D.** It restores the 1,150 km that SPEC\n"
        "§2.1.1 warned would cost *more* to sweep up later than to drive now, and it reverses\n"
        "the project's only §1.1 override. What it costs is "
        f"{_n(d10['days'] - inputs['variants']['C']['10h']['days'])} more days of driving and\n"
        "about forty minutes of recompute.\n"
        "\nThe margin is not the same at both windows: "
        f"**+{_n(d10['margin_days'])} days at 10 h** but only\n"
        f"**+{_n(inputs['variants']['D']['9h']['margin_days'])} at 9 h**. If the shift decision\n"
        "lands on the 9 h window, D is still inside the limit but has under a week of slack,\n"
        "and any slippage in Stage 5 eats it. The two decisions are coupled and should not be\n"
        "taken in ignorance of each other.\n",
        "Three things should be decided together rather than in sequence, because each is\n"
        "cheap only while the others are being done:\n"
        "\n"
        f"1. **Scope** — D rather than C, on the numbers in §1.\n"
        "2. **The mainline-entry narrowing** (§2), which needs a rebuild of Stages 1–4 that a\n"
        "   scope change is already paying for.\n"
        "3. **The reserved commute allowance** (§3), which is already the default and will be\n"
        "   re-derived on D's own numbers by that rebuild.\n"
        "\n"
        "**Stage 5 should not start until this is settled.** It consumes the zones, and all\n"
        "three of the above change them.\n",
        "What remains undecided either way is the residual unreachable requirement — "
        f"{_km(recheck['D']['unreachable_km'])} km under D, of which the clip-edge and\n"
        "base-topology parts are not fixable by any rule. SPEC §1.1 still wants a disposition\n"
        "on those before Stage 5, and this stage does not provide one: they are reported, not\n"
        "resolved.\n",
    )


def _gate(a: dict) -> str:
    fix = a["item2_trap_disposition"]["fix"]
    inputs = a["decision_inputs"]
    return _block(
        "\n## 5. Gate\n",
        _table(
            ["Assertion", "Value"],
            [
                ["Variant D measured, not scaled from C",
                 "full Stage 4 pipeline at `VARIANT = D`"],
                ["Every variant/window combination inside the daylight limit",
                 " · ".join(
                     f"{v} {w}: {'yes' if row['fits'] else 'NO'}"
                     for v, rows in sorted(inputs["variants"].items())
                     for w, row in sorted(rows.items())
                 )],
                ["Trapped mainlines attributed to a cause", "yes, by counterfactual rebuild"],
                ["Fix adds only manoeuvres, never removes",
                 f"+{_n(fix['edges_added'])} manoeuvres, 0 removed"],
                ["Invariant U1 after the fix",
                 f"exhaustive over {_n(fix['u1']['checked'])} additions, "
                 f"{_n(fix['u1']['violations'])} violations"],
                ["Defaults changed by this stage",
                 f"`COMMUTE_ALLOWANCE` only (now {_f(C.COMMUTE_ALLOWANCE, 2)})"],
                ["Scope variant", f"unchanged — still `{a['current_scope_variant']}`"],
                ["`network.gpkg` sha256", f"`{a['meta']['arcs_sha256'][:16]}…`"],
            ],
            numeric=False,
        ),
        "\n### Non-goals honoured\n",
        "No scope decision was taken — the numbers are here and the decision is not this\n"
        "stage's to make. The mainline-entry narrowing is proposed and measured, not\n"
        "adopted. No Stage 4 artifact for the committed scope was overwritten: every\n"
        "alternative wrote to `04b-*`.\n",
    )
