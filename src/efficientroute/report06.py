"""Render `reports/06-day-NN.md` — what the car actually did, and what is left.

Every number is read from `06-coverage-state.json` and the day's own outcome, and
the report is written to be read by whoever is running the campaign rather than by
whoever wrote the solver: what got covered, what did not and why, what the trace
says about the model's guesses, and when this now finishes.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

from . import caveat
from . import config as C
from .report import _table
from .report02 import _block, _f, _h, _n

REASON_LABEL = {
    "counted": "covered",
    "partial": "only part of the street was driven",
    "speed": "driven too fast to film",
    "heading": "driven the wrong way",
    "not-recording": "the rig was not recording",
    "no-time": "the trace had no timestamps, so speed could not be checked",
    "retired": "retired by an exception",
    "satisfied": "already covered",
}


def write(a: dict, path: Path) -> Path:
    parts = [f"# Stage 6 — day {a['day']:02d}, {a['date']}\n"]
    parts.append(
        "Generated by `efficientroute stage6`. Every number is read from\n"
        "`data/derived/06-coverage-state.json`, which the Stage 6 gate asserts against."
    )
    parts.append(_headline(a))
    parts.append(_what_counted(a))
    parts.append(_exceptions(a))
    parts.append(_calibration(a))
    parts.append(_remaining(a))
    path.parent.mkdir(parents=True, exist_ok=True)
    caveat.write(path, _block(*parts))
    return path


def _headline(a: dict) -> str:
    return (
        "\n## Headline\n\n"
        f"> ## {_n(a['gained'])} required elements covered\n"
        f">\n"
        f"> Campaign now **{_f(100 * a['coverage_fraction'], 1)}%** complete —\n"
        f"> {_n(a['covered_total'])} of {_n(a['required_total'])} elements, with\n"
        f"> {_n(a['outstanding'])} still owed.\n"
        f">\n"
        f"> Recording evidence: **{a['recording_evidence']}**.\n"
    )


def _what_counted(a: dict) -> str:
    counts = Counter(a["reasons"])
    rows = [
        [REASON_LABEL.get(name, name), f"`{name}`", _n(count)]
        for name, count in counts.most_common()
    ]
    parts = [
        "\n## 1. What the trace counted, and what it did not",
        _table(["Outcome", "Reason code", "Traversals"], rows),
    ]
    if a["recording_evidence"] == "unknown":
        parts.append(
            "**The camera cannot be verified.** A GPS trace is evidence the car was\n"
            "there, not that the rig was recording, and the Stereolabs output is not\n"
            "known to expose footage timestamps (`config.RECORDING_EVIDENCE_AVAILABLE`\n"
            "is False). Every figure above assumes the camera was on whenever the car\n"
            "was moving. If that assumption is wrong the coverage is overstated, and\n"
            "no number here would show it — this is the largest unverified assumption\n"
            "in the campaign's coverage figure."
        )
    if a.get("wrong_way"):
        parts.append(
            f"**{_n(len(a['wrong_way']))} street(s) were driven the wrong way** and did\n"
            "not count. They are still owed, and the driver should be told before "
            "tomorrow rather than after the footage review."
        )
    return _block(*parts)


def _exceptions(a: dict) -> str:
    register = a["exceptions"]
    if not register["entries"]:
        return _block("\n## 2. Exceptions", "None recorded. Nothing has been retired.")
    return _block(
        "\n## 2. Exceptions",
        _table(
            ["Retired today", "Returned today", "On the register", "Retired total"],
            [[_n(len(register["retired_keys"])), _n(len(register["restored_keys"])),
              _n(register["entries"]), f"{_f(register['retired_km'], 2)} km"]],
        ),
        f"**{_f(register['retired_km'], 2)} km has been retired.** That is coverage the\n"
        "campaign will never achieve, and it belongs in the completion figure rather\n"
        "than hidden behind it: complete coverage now means everything except this.",
    )


def _calibration(a: dict) -> str:
    turns = a["calibration"]["turns"]
    if not turns:
        return _block("\n## 3. Calibration",
                      "No junction observations in this trace.")
    rows = [
        [name, _f(stats["assumed_s"], 1) if stats["assumed_s"] is not None else "—",
         _f(stats["measured_s"], 2), _f(stats["p25_s"], 2), _f(stats["p75_s"], 2),
         _n(stats["n"])]
        for name, stats in sorted(turns.items())
    ]
    parts = [
        "\n## 3. Calibration — what the trace says about the model's guesses",
        _table(["Turn", "Assumed s (SPEC §3.3)", "Measured s", "p25", "p75", "n"], rows),
    ]
    if not a["calibration"].get("is_evidence", True):
        return _block(
            *parts,
            "**These numbers are not evidence about Tbilisi.** This trace is a replay\n"
            "of a planned route, so the only junction delays in it are the ones the\n"
            "replay put there — a simulated car does not slow for a corner it was\n"
            "never told about. The table shows the extractor working against a known\n"
            "answer, nothing more. SPEC §3.3's penalties stay **[CONFIRM]** until a\n"
            "real day is driven.",
        )
    return _block(
        *parts,
        "SPEC §3.3's turn penalties are the spec's own approximations, still marked\n"
        "**[CONFIRM values]**, and turn time is 17.4% of all driving — every turn\n"
        "figure in this project scales linearly with them.\n"
        "\n**Nothing above has been adopted.** CLAUDE.md's rule on calibration "
        "constants applies: a constant is pinned deliberately, with a measured\n"
        "justification, never refreshed automatically. Changing a penalty changes\n"
        "every route and every finish date, so it is a reviewed act — these are the\n"
        "measurements to review, not a change that has happened.",
    )


def _remaining(a: dict) -> str:
    finish = a.get("revised_finish")
    parts = ["\n## 4. What is left"]
    parts.append(
        _table(
            ["Required", "Covered", "Retired", "Still owed"],
            [[_n(a["required_total"]), _n(a["covered_total"]),
              _n(a["retired_total"]), _n(a["outstanding"])]],
        )
    )
    if finish:
        parts.append(
            f"Re-planned over the remainder: **{_n(finish['days'])} days**, finishing\n"
            f"**{finish['finish']}** ({_h(finish['route_h'])} h of driving)."
        )
    else:
        parts.append(
            "The remaining set has been written to "
            f"`{C.OUTSTANDING_JSON.name}`. Stages 4 and 5 read it when it is present,\n"
            "so `make stage4 && make stage5` re-plans the remainder — the later stages\n"
            "do not know or care which day it is. Run `efficientroute stage6 --replan`\n"
            "to do both in one step and get a revised finish date here."
        )
    return _block(*parts)
