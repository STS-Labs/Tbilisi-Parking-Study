"""Render the two deliverables a customer campaign owes: reconciliation and summary.

Both are written from artifacts on disk — this campaign's under `OUTPUT_ROOT`, and
the Tbilisi run's from the repository root for comparison — so they regenerate
without re-solving anything.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import caveat
from . import config as C
from .report import _table
from .report02 import _block, _f, _h, _n

REPO = Path(__file__).resolve().parents[2]


def _read(path: Path) -> dict:
    return json.loads(Path(path).read_text())


def gather() -> dict:
    zone = {name: _read(C.DERIVED / f"{name}.json") for name in
            ("00-network-stats", "00b-service-scenarios", "03-bounds",
             "04-zones", "05-routes", "CUSTOM-reconciliation")}
    tbilisi = {name: _read(REPO / "data" / "derived" / f"{name}.json") for name in
               ("00-network-stats", "00b-service-scenarios", "03-bounds", "05-routes")}
    return {"zone": zone, "tbilisi": tbilisi}


def _variant_c(payload: dict) -> dict:
    return {v["variant"]: v for v in payload["variants"]}["C"]


def write_reconciliation(data: dict, path: Path | None = None) -> Path:
    path = Path(path or C.REPORTS / "CUSTOM-reconciliation.md")
    r = data["zone"]["CUSTOM-reconciliation"]
    cust, osm = r["customer"], r["osm"]

    parts = ["# Zone B — reconciliation against the customer's street layer\n"]
    parts.append(
        "Generated by `efficientroute custom-report`. Every number is read from\n"
        "`data/derived/CUSTOM-reconciliation.json`.\n"
        "\nThe customer layer carries no name, class or `oneway` — only an `Id` of zero\n"
        "and a stale `Length` — so nothing can be joined on. Streets are matched by\n"
        f"**geometric proximity within {r['tolerance_m']:.0f} m**, and measured as\n"
        "**length**, not as features: 3,368 customer parts against a directed arc table\n"
        "is not a comparison, and a street half-present should come out half-matched\n"
        "rather than being forced into a yes or a no."
    )

    parts.append(_block(
        "\n## Headline",
        f"> ## {_h(cust['unmatched_km'])} km of the customer's streets are not in OSM\n"
        f">\n"
        f"> They will **never be covered** by this plan, whatever it does. That is\n"
        f"> {100 - cust['matched_pct']:.1f}% of the {_h(cust['total_km'])} km supplied,\n"
        f"> across {_n(cust['unmatched_features'])} separate parts.\n"
        f">\n"
        f"> Going the other way, the plan drives {_h(osm['extra_km'])} km the customer\n"
        f"> did not ask for.",
    ))

    parts.append(_block(
        "\n## 1. In the customer's layer, not in OSM — never covered",
        _table(
            ["", "km", "share"],
            [["Supplied by the customer", _h(cust["total_km"]), "100.0%"],
             ["Matched in OSM", _h(cust["matched_km"]), f"{cust['matched_pct']:.1f}%"],
             ["**Not in OSM — never covered**", f"**{_h(cust['unmatched_km'])}**",
              f"**{100 - cust['matched_pct']:.1f}%**"]],
        ),
        "The customer layer has no class attribute, so this cannot be broken down by\n"
        "road type — only located. The longest unmatched pieces:",
        _table(
            ["Missing m", "of total m", "Longitude", "Latitude"],
            [[_f(row["missing_m"], 1), _f(row["total_m"], 1),
              f"{row['lon']:.5f}", f"{row['lat']:.5f}"]
             for row in r["worst_missing"][:15]],
        ),
        "**What this most likely is.** A street present on the ground and absent from\n"
        "OSM, or one OSM records with different geometry than the customer's survey.\n"
        "Either way the plan cannot drive what the network does not contain, so this\n"
        "figure is a hard ceiling on coverage and belongs in the contract rather than\n"
        "in a footnote.",
    ))

    parts.append(_block(
        "\n## 2. In OSM, not in the customer's layer — unasked-for work",
        _table(
            ["", "km", "share"],
            [["OSM required in Zone B", _h(osm["total_km"]), "100.0%"],
             ["Matched in the customer layer", _h(osm["matched_km"]),
              f"{osm['matched_pct']:.1f}%"],
             ["Extra — not requested", _h(osm["extra_km"]),
              f"{100 - osm['matched_pct']:.1f}%"]],
        ),
        "By highway class:",
        _table(["Class", "km"],
               [[k, _f(v, 3)] for k, v in list(r["extra_by_class"].items())[:10]]),
        f"{_h(osm['extra_km'])} km is small enough to be digitising difference rather\n"
        "than genuine scope creep, and most of it is trunk and link geometry at the\n"
        "zone edge where the two surveys drew the carriageway differently.",
    ))

    parts.append(_block(
        "\n## 3. Reconciling against the customer's stated total",
        _table(
            ["", "km"],
            [["Customer's stated total", "347.0"],
             ["Measured from the shapefile", _h(cust["total_km"])],
             ["  of which matched in OSM", _h(cust["matched_km"])],
             ["  of which not in OSM", _h(cust["unmatched_km"])],
             ["**Sum**", f"**{_h(cust['matched_km'] + cust['unmatched_km'])}**"]],
        ),
        "The measured total agrees with the stated 347.0 km, so the gap is entirely\n"
        "between the two surveys and not an artefact of how this was counted.",
    ))
    path.parent.mkdir(parents=True, exist_ok=True)
    caveat.write(path, _block(*parts))
    return path


#: Constants this campaign inherited rather than measured. The brief is explicit
#: that they must be listed as such: a number carried from another city is a
#: hypothesis about this one until its own Stage 5 reports back.
TRANSFERRED = [
    ("`ZONE_OVERHEAD_MEASURED`", "2.2598", "Tbilisi p75, 49 solved days",
     "Zone B measures 2.7297 — 20.8% higher"),
    ("`TURN_PENALTY_S`", "left 8 s / right 3 s / u-turn 20 s",
     "SPEC §3.3 estimate, never measured", "still **[CONFIRM]**; 23.2% of driving here"),
    ("Speed model coefficients", "as fitted for Tbilisi", "Stage 2 free-flow + gradient",
     "unchanged; no Zone B traces exist to refit from"),
    ("Congestion multipliers", "by class x time band", "Tbilisi assumption",
     "unchanged"),
    ("`CAPTURE_SPEED_MAX_KMH`", "40", "SPEC §5, confirmed", "policy, not a measurement"),
    ("`MATCH_MAX_CANDIDATE_DIST_M`", "25", "provisional, never calibrated",
     "no real trace in either campaign"),
]


def write_summary(data: dict, verification: dict, path: Path | None = None) -> Path:
    path = Path(path or C.REPORTS / "CUSTOM-SUMMARY.md")
    z, t = data["zone"], data["tbilisi"]
    z5, t5 = z["05-routes"]["totals"], t["05-routes"]["totals"]
    zc = _variant_c(z["00b-service-scenarios"])["required_traversal_km"]
    tc = _variant_c(t["00b-service-scenarios"])["required_traversal_km"]
    ra = z["00-network-stats"]["required_area"]
    rec = z["CUSTOM-reconciliation"]
    z3 = {v["variant"]: v for v in z["03-bounds"]["variants"]}["C"]
    t3 = {v["variant"]: v for v in t["03-bounds"]["variants"]}["C"]
    zone_h_km, tb_h_km = z5["route_h"] / zc, t5["route_h"] / tc

    parts = ["# Zone B — campaign summary\n"]
    parts.append(
        "Generated by `efficientroute custom-report`. Every number is read from the\n"
        "artifacts under `CUSTOM-OUTPUT/data/derived/`, and the Tbilisi figures from\n"
        "`data/derived/` for comparison."
    )
    parts.append(
        "\n## Headline\n\n"
        f"> ## {_n(z5['days'])} driving days, {z5['start_date']} → {z5['finish_date']}\n"
        f">\n"
        f"> **{_h(z5['route_h'])} h** of driving — {_h(z5['capture_h'])} h capture,\n"
        f"> {_h(z5['deadhead_h'])} h deadhead, {_h(z5['turn_h'])} h turns — to cover\n"
        f"> **{_h(zc)} km** of required traversal inside a {_h(ra['included_km'])} km\n"
        f"> drivable clip. No day exceeds its window.\n"
        f">\n"
        f"> **{_h(rec['customer']['unmatched_km'])} km of the customer's own streets are\n"
        f"> not in OSM and will never be covered.**"
    )

    parts.append(_block(
        "\n## 1. The plan",
        _table(
            ["", "Zone B"],
            [["Driving days", _n(z5["days"])],
             ["Dates", f"{z5['start_date']} → {z5['finish_date']}"],
             ["Zones (before splitting)", _n(len(z["04-zones"]["windows"]["9h"]["zones"]))],
             ["Zones split by Stage 5", _n(len(z["05-routes"]["splits"]))],
             ["Required traversal (variant C)", f"{_h(zc)} km"],
             ["Total driving", f"{_h(z5['route_h'])} h"],
             ["  capture", f"{_h(z5['capture_h'])} h"],
             ["  deadhead", f"{_h(z5['deadhead_h'])} h"],
             ["  turns", f"{_h(z5['turn_h'])} h"],
             ["Days over window", _n(z5["days_over_window"])],
             ["Stage 3 bracket", f"{_h(t3['lower_bound_h']) if False else _h(z3['lower_bound_h'])}"
                                 f" – {_h(z3['total_h'])} h"]],
            numeric=False,
        ),
        "**Required is a strict subset of routable for the first time.** "
        f"{_h(ra['required_km'])} km of arc length is required out of {_h(ra['included_km'])} km "
        f"drivable ({ra['required_share_pct']:.1f}%); the rest is the 2 km buffer the car may "
        "cross to reach the zone and to get home. That makes this a genuine Rural "
        "Postman instance rather than the Chinese Postman every previous run reduced to.",
        f"**{_h(ra['near_boundary_km'])} km sits within {ra['margin_m']:.0f} m of the zone "
        "edge**, where an arc is required or not on whether its midpoint falls inside. "
        "That is the arbitrary part of the boundary rule and the most likely place for "
        "a customer to dispute a street being skipped.",
    ))

    parts.append(_block(
        "\n## 2. Against the Tbilisi run — is a small dense zone cheaper per km?",
        _table(
            ["", "Tbilisi", "Zone B", "Zone B vs Tbilisi"],
            [["Required traversal", f"{_h(tc)} km", f"{_h(zc)} km",
              f"{zc / tc * 100:.1f}% of the size"],
             ["Driving days", _n(t5["days"]), _n(z5["days"]), ""],
             ["Total driving", f"{_h(t5['route_h'])} h", f"{_h(z5['route_h'])} h", ""],
             ["**Hours per required km**", f"**{tb_h_km:.4f}**", f"**{zone_h_km:.4f}**",
              f"**{(zone_h_km / tb_h_km - 1) * 100:+.1f}%**"],
             ["Deadhead / capture", f"{100 * t5['deadhead_h'] / t5['capture_h']:.1f}%",
              f"{100 * z5['deadhead_h'] / z5['capture_h']:.1f}%",
              f"{100 * (z5['deadhead_h'] / z5['capture_h'] - t5['deadhead_h'] / t5['capture_h']):+.1f} pp"],
             ["Turn share of driving", f"{100 * t5['turn_h'] / t5['route_h']:.1f}%",
              f"{100 * z5['turn_h'] / z5['route_h']:.1f}%",
              f"{100 * (z5['turn_h'] / z5['route_h'] - t5['turn_h'] / t5['route_h']):+.1f} pp"],
             ["Required km per day", f"{tc / t5['days']:.1f}", f"{zc / z5['days']:.1f}",
              f"{(zc / z5['days']) / (tc / t5['days']) * 100 - 100:+.1f}%"],
             ["Measured intra-zone overhead (p75)",
              f"{t['05-routes']['overhead_measured']['p75']:.4f}",
              f"{z['05-routes']['overhead_measured']['p75']:.4f}",
              f"{(z['05-routes']['overhead_measured']['p75'] / t['05-routes']['overhead_measured']['p75'] - 1) * 100:+.1f}%"]],
            numeric=False,
        ),
        "**The answer: almost exactly the same per kilometre, and for entirely "
        "different reasons.**",
        f"Zone B costs {zone_h_km:.4f} h per required km against Tbilisi's {tb_h_km:.4f} — "
        f"{abs(zone_h_km / tb_h_km - 1) * 100:.1f}% apart, which is noise at this sample "
        "size. Underneath, three things move in opposite directions and happen to "
        "cancel:",
        "- **Deadhead is worse** — 102% of capture against 90%. Required is a subset of "
        "routable here, so the car repeatedly crosses streets it is not being paid to "
        "film, which the Tbilisi problem structurally could not do.\n"
        "- **Turns are worse** — 23.2% of all driving against 17.6%. A dense inner zone "
        "is mostly junctions, and SPEC §3.3's turn penalties are the largest unmeasured "
        "assumption in that number.\n"
        "- **Capture is cheaper per km** — short urban blocks, low free-flow speeds, and "
        "no long fast arterials on which the 40 km/h capture cap bites.",
        f"**What prices a future job is the day rate, not the km rate.** Zone B covers "
        f"{zc / z5['days']:.1f} required km per driving day against Tbilisi's "
        f"{tc / t5['days']:.1f} — "
        f"{100 - (zc / z5['days']) / (tc / t5['days']) * 100:.0f}% fewer. A small dense "
        "zone costs about the same per kilometre but delivers fewer kilometres per day, "
        "so quote it by the day and expect the depot leg to be cheap and the junctions "
        "to be expensive.",
    ))

    parts.append(_block(
        "\n## 3. Reconciliation",
        _table(
            ["", "km", "share"],
            [["Customer supplied", _h(rec["customer"]["total_km"]), "100.0%"],
             ["Matched in OSM", _h(rec["customer"]["matched_km"]),
              f"{rec['customer']['matched_pct']:.1f}%"],
             ["**Not in OSM — never covered**", f"**{_h(rec['customer']['unmatched_km'])}**",
              f"**{100 - rec['customer']['matched_pct']:.1f}%**"],
             ["OSM extra, not requested", _h(rec["osm"]["extra_km"]),
              f"{100 - rec['osm']['matched_pct']:.1f}% of OSM"]],
        ),
        f"Full detail in `CUSTOM-reconciliation.md`. Matched by geometry within "
        f"{rec['tolerance_m']:.0f} m; the customer layer has no attributes to join on.",
    ))

    parts.append(_block(
        "\n## 4. Constants transferred, not measured for this zone",
        _table(["Constant", "Value used", "Where it came from", "What Zone B says"],
               [list(row) for row in TRANSFERRED], numeric=False),
        "**The overhead is the one that cost days.** Sizing used Tbilisi's 2.2598 as the "
        "brief instructed; Zone B actually drives 2.7297, 20.8% higher, and three of the "
        "four zones overran their window and had to be split — which is why this is 7 "
        "days and not 4. Per CLAUDE.md the constant is pinned, not fed back, so it has "
        "**not** been re-derived mid-run. Re-sizing on the measured figure is a "
        "deliberate, reviewed act and the obvious next step for a second Zone B "
        "campaign.",
    ))

    parts.append(_block(
        "\n## 5. Decisions I had to make",
        _table(["Decision", "Choice", "Why"],
               [list(row) for row in verification["decisions"]], numeric=False),
    ))

    parts.append(_block(
        "\n## 6. Gates",
        _table(["Gate", "Result"], [list(row) for row in verification["gates"]],
               numeric=False),
        verification["gate_note"],
    ))

    parts.append(_block(
        "\n## 7. The Tbilisi plan is untouched",
        verification["tbilisi"],
    ))
    path.parent.mkdir(parents=True, exist_ok=True)
    caveat.write(path, _block(*parts))
    return path
