#!/usr/bin/env python3
"""Write `reports/08-SUMMARY.md` — does the Stage 8 saving generalise?

Four campaigns over the same city, differing in size (7 to 47 days) and in how dense
the required set is inside the network that connects it (24.9% to 39.6%). If the
saving is a property of coverage planning it should appear in all four; if it is a
property of one geometry it will not.

Reads each campaign's `08-sequential.json` and writes one table. Nothing here
recomputes anything — every number is the one that campaign's own gate asserted.

Usage:  PYTHONPATH=src uv run python tools/stage8_summary.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
CAMPAIGNS = [
    ("Tbilisi", ".", "whole city, variant C"),
    ("Zone B — variant C", "CUSTOM-OUTPUT", "24 km² zone, service excluded"),
    ("Run 1 — OSM full", "RUN-OSM-FULL", "same zone, service included"),
    ("Run 2 — customer net", "RUN-CUSTOMER-NET", "same zone, customer's street list"),
]
OUT = ROOT / "reports" / "08-SUMMARY.md"

rows = []
for name, root, note in CAMPAIGNS:
    path = ROOT / root / "data" / "derived" / "08-sequential.json"
    if not path.exists():
        print(f"  missing {path} — run `sh tools/stage8-all.sh` first", file=sys.stderr)
        continue
    payload = json.loads(path.read_text())
    base = payload["baseline"]
    adopted = payload["adopted"]
    tier = payload["tiers"].get(adopted, base)
    tier1 = payload["tiers"].get("1")
    rows.append({
        "name": name, "note": note, "base": base, "tier": tier, "tier1": tier1,
        "adopted": adopted, "attempts": payload.get("attempts") or [],
    })

if not rows:
    raise SystemExit("no campaign artifacts found")


def pct(tier, base):
    return 100.0 * (tier["route_h"] - base["route_h"]) / base["route_h"]


lines = [
    "# Stage 8 across every campaign — does the saving generalise?\n",
    "Generated by `tools/stage8_summary.py` from each campaign's",
    "`data/derived/08-sequential.json`. Nothing is recomputed here; every number is",
    "the one that campaign's own Stage 8 gate asserted.\n",
    "\n## The answer: yes, on hours — on days it depends on the geometry\n",
    "\n| Campaign | | Before | After | Δ days | Δ hours | Credited | Cost of credit |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
]
for r in rows:
    base, tier = r["base"], r["tier"]
    d = tier.get("vs_baseline", {"days": 0, "route_h": 0.0})
    lines.append(
        f"| **{r['name']}** | {r['note']} | "
        f"{base['days']} d, {base['route_h']:.1f} h | "
        f"{tier['days']} d, {tier['route_h']:.1f} h | "
        f"**{d['days']:+d}** | **{d['route_h']:+.1f} h** ({pct(tier, base):+.1f}%) | "
        f"{tier.get('bonus_km', 0.0):.0f} km | "
        f"{tier.get('slowing_h', 0.0) * 60:.0f} min |"
    )

lines += [
    "\n**Every campaign saves hours, and every campaign saves them the same way.**",
    "The credit is bought at a few seconds per kilometre — the slowdown from",
    "repositioning speed to filming speed on streets the car was already driving —",
    "and it is repaid by a revisit that never has to happen.\n",
    "\n## What each tier bought\n",
    "\n| Campaign | Tier 0 | Tier 1 — passive credit | Tier 2 — order search |",
    "| --- | ---: | ---: | ---: |",
]
for r in rows:
    base, t1, t2 = r["base"], r.get("tier1"), r["tier"]
    one = f"{t1['days']} d, {t1['route_h']:.1f} h" if t1 else "—"
    two = (f"{t2['days']} d, {t2['route_h']:.1f} h"
           if r["adopted"] == "2" else "no gain over tier 1")
    lines.append(f"| {r['name']} | {base['days']} d, {base['route_h']:.1f} h | "
                 f"{one} | {two} |")

lines += [
    "\n**Tier 1 is where the hours come from; tier 2 is where the days come from.**",
    "Passive crediting — banking passes the route already drives — takes most of the",
    "driving time out. Changing *which day runs first* then removes days on top,",
    "because credit lands on whichever days go early and Stage 4's far-zones-first",
    "sequence was chosen to shorten depot legs by a rule that predates crediting.\n",
    "\n## Where it does not help\n",
    "\nTbilisi saves hours and **no days**. The reason is structural rather than",
    "disappointing: its 47 zones are each sized to fill a shift, so removing work from",
    "one shortens it without emptying it, and a day only disappears when a zone owes",
    "nothing at all. The zone campaigns have fewer, lumpier zones, so credit can empty",
    "one outright — and, more often, can stop one from overrunning its window and",
    "being split into two.\n",
    "\n**So the saving scales with hours, not with days.** Quote by the day and the",
    "gain shows up on a small campaign; quote by the hour and it shows up everywhere.\n",
    "\n## What was not built\n",
    "\n§2 of the brief asks for Large Neighbourhood Search over day assignments, with",
    "relocate, swap, fragment-relocate, spatial ruin-and-recreate and merge-day moves.",
    "**Only the order-search member of that family was implemented.** The rest is not",
    "attempted, and the honest reason is that each LNS move needs the affected days",
    "re-solved as routes rather than re-costed — a Tbilisi day solve is roughly ten",
    "seconds, so a search of any depth is hours of compute per campaign and belongs on",
    "its own brief with a time budget attached.\n",
    "\n**Active detour — tier 2 as the brief defines it — is not implementable in this",
    "formulation at all.** `lstar.build` enforces `capture >= deadhead`, because the",
    "capture cap can only slow the car down (SPEC §6). Filming an arc you are passing",
    "is therefore never cheaper than passing it, so a single day's min-cost flow can",
    "never prefer to film: the entire reason to film is a saving on a *later* day,",
    "which the day's own objective cannot see. Expressing it needs a negative-cost",
    "reward, which the flow forbids. Crediting after the route is known — tier 1 — is",
    "the correct workaround rather than a shortcut, and it is why tier 1 does the",
    "heavy lifting.\n",
    "\n## The invariants, on every campaign\n",
    "\n| Campaign | Requirements undischarged | I9 failures | I10 costing | Days over window |",
    "| --- | ---: | ---: | --- | ---: |",
]
for r in rows:
    t = r["tier"]
    lines.append(
        f"| {r['name']} | {t.get('undischarged_passes', 0)} | "
        f"{len(t.get('i9_failures', []))} | "
        f"{'holds' if t.get('i10_ok') else '**FAILS**'} | "
        f"{t.get('days_over_window', 0)} |"
    )
lines += [
    "\n**I9 is asserted against `coverage.qualifies`, the same function Stage 6 applies",
    "to a real GPS trace.** One implementation, two callers, so plan-time and run-time",
    "crediting cannot drift — a plan that banked coverage the rig does not deliver",
    "would be the Stage 6 failure arriving a stage earlier and much harder to see.\n",
]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT}")
